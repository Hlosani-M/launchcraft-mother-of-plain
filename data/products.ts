/**
 * Catalogue for the website demonstration.
 *
 * Products marked `birthdayBash()` and their prices come from the store's
 * 19th Birthday Bash catalogue (valid 21–31 Oct 2026, while stocks last, E&OE).
 * Hamper prices and the extra Rainbow range are samples. Product photos are
 * supplied by the store, cropped from its catalogue, or openly licensed
 * Wikimedia Commons photos (credited in data/imageCredits.ts and on /credits).
 * All are "for illustration only".
 */

type ProductInput = Omit<Product, "id" | "isFeatured" | "isSpecial"> &
  Partial<Pick<Product, "isFeatured" | "isSpecial">>;

function product(input: ProductInput): Product {
  return { id: input.slug, isFeatured: false, isSpecial: false, ...input };
}

/** A product on the current promotion, with its validity dates. */
function birthdayBash(input: ProductInput): Product {
  return product({
    isSpecial: true,
    specialLabel: currentPromotion.name,
    specialValidFrom: currentPromotion.validFrom,
    specialValidTo: currentPromotion.validTo,
    ...input,
  });
}

